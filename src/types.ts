export type ObservationStatus = 'سليم' | 'يحتاج معالجة' | '';
export type ReportType = 'daily' | 'weekly' | 'item';

export interface ObservationItem {
  id: string;
  description: string;
  status: ObservationStatus;
}

export interface AttachedImage {
  id: string;
  dataUrl: string;
  caption: string;
}

export interface ReportData {
  id?: string;
  reportType?: ReportType;
  targetDomain?: string; // For independent item reports
  dayName?: string;
  weekNumber?: string;
  weekDateRange?: string;
  semester?: string;
  title: string;
  dateDay: string;
  dateMonth: string;
  dateYear: string;
  preparedBy: string;
  timeOfDay: 'صباحاً' | 'مساءً' | '';
  selectedDomains: string[];
  otherDomain: string;
  domainDetails?: string;
  observations: ObservationItem[];
  recommendations: string;
  schoolAgentName: string;
  schoolPrincipalName: string;
  images?: AttachedImage[];
}

export interface SavedReport {
  id: string;
  title: string;
  reportType: ReportType;
  targetDomain?: string;
  dateString: string;
  dayName?: string;
  createdAt: string;
  updatedAt: string;
  observationsCount: number;
  data: ReportData;
}

